"""One-shot LinkedIn recovery check — fires ~8:52 PM (when the recovery pause lifts).
Clears the recovery pause, probes LinkedIn ONCE (the hardened health check auto-backs-off
HARD if still blocked), resumes the radar if healthy, and writes a human-readable status to
data/recovery_status.md so the user sees the outcome when they return."""
import asyncio
import json
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).parent.parent
STATUS = ROOT / "data" / "recovery_status.md"
STATE = ROOT / "data" / "pipeline_state.json"


async def main():
    from agents.monitoring.linkedin_health import run_health_check, _PAUSE_FILE

    # Clear the recovery pause so the probe actually runs (run_health_check skips when paused).
    try:
        if _PAUSE_FILE.exists():
            _PAUSE_FILE.unlink()
    except Exception:
        pass

    status = await run_health_check()   # probes feed; re-pauses HARD if still blocked
    healthy = (status == "ok")

    try:
        s = json.loads(STATE.read_text())
        q = dict(Counter(a.get("status") for a in s.get("applications", [])))
    except Exception:
        q = {}

    now = datetime.now(timezone.utc)
    lines = [
        f"# LinkedIn Recovery Check — {now.strftime('%Y-%m-%d %H:%M UTC')}",
        "",
        f"**LinkedIn health:** `{status}`",
        ("✅ **RECOVERED** — the human-like radar is back online and will resume scanning on its "
         "~2h cadence, feeding fresh roles into the apply pipeline overnight."
         if healthy else
         "⚠️ **Still blocked** — LinkedIn is not clear yet. It auto-backed-off again (hours). "
         "When you're back, refresh the `li_at` cookie and tell Claude 'check LinkedIn', or wait longer."),
        "",
        "## Queue right now",
        f"- pending_review (ready to apply): **{q.get('pending_review', 0)}**",
        f"- submitted: {q.get('submitted', 0)}  ·  manual: {q.get('pending_manual_submit', 0)}",
        "",
        "## Next",
        ("- Radar active → fresh LinkedIn roles flow in automatically.\n"
         "- The off-LinkedIn apply pipeline keeps running every 3h regardless."
         if healthy else
         "- Off-LinkedIn apply pipeline still runs every 3h (no account needed).\n"
         "- Open the review queue + apply to the pending ones via the extension anytime."),
        "",
        f"_(auto-generated by recovery_check at {now.strftime('%H:%M UTC')})_",
    ]
    STATUS.write_text("\n".join(lines))
    print(f"recovery_check: health={status} healthy={healthy} pending={q.get('pending_review', 0)}")


asyncio.run(main())
